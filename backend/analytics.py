# Live state, derived quantities
# ---------------------------------------------------------------------------
def derived_state(reading: Dict) -> Dict:
    """Turn one raw sensor reading into every derived quantity, with formulas."""
    v = float(reading.get("voltage") or 0)
    i = float(reading.get("current") or 0)
    t = float(reading.get("temperature") or 25)
    light = float(reading.get("light") or 0)
    bv = float(reading.get("battery_v") or C.BATTERY_NOMINAL_V)
    load_w = float(reading.get("load_power") or 0)

    p = F.power(v, i)
    irr = F.irradiance_from_light(light)
    ct = F.cell_temperature(t, irr.value or 0)
    soc = F.soc_from_voltage(bv)
    usable = F.usable_battery_energy(soc.value or 0)
    auton = F.autonomy_hours(usable.value or 0, load_w)
    eff = F.panel_efficiency(p.value or 0, irr.value or 0)
    expected = F.temperature_derated_power(irr.value or 0, ct.value or 25)
    resid = F.prediction_residual(p.value or 0, expected.value or 0)

    calcs = [p, irr, ct, soc, usable, auton, eff, expected, resid]
    return {
        "values": {c.key: c.value for c in calcs},
        "formulas": [c.to_dict() for c in calcs],
    }


