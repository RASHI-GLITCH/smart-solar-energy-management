# Correlations  (feeds the Neo4j graph)
# ---------------------------------------------------------------------------
CORR_VARS = ["power", "voltage", "current", "temperature", "light",
             "battery_v", "load_power"]

PRETTY = {
    "power": "PV Power", "voltage": "Panel Voltage", "current": "Panel Current",
    "temperature": "Temperature", "light": "Light / Irradiance",
    "battery_v": "Battery Voltage", "load_power": "Load Power",
}

UNITS = {"power": "W", "voltage": "V", "current": "A", "temperature": "degC",
         "light": "ADC", "battery_v": "V", "load_power": "W"}


def correlations(min_abs_r: float = 0.15, days: int = 14) -> Dict:
    """Pairwise Pearson correlation between every measured variable."""
    df = get_history(days=days)
    cols = [c for c in CORR_VARS if c in df.columns and df[c].notna().sum() > 10]
    if len(cols) < 2:
        return {"error": "Not enough varying data to compute correlations.",
                "nodes": [], "edges": []}

    nodes, edges, calcs = [], [], []
    for c in cols:
        series = pd.to_numeric(df[c], errors="coerce").dropna()
        nodes.append({
            "id": c,
            "label": PRETTY.get(c, c),
            "unit": UNITS.get(c, ""),
            "mean": round(float(series.mean()), 3),
            "min": round(float(series.min()), 3),
            "max": round(float(series.max()), 3),
            "std": round(float(series.std()), 3),
            "samples": int(len(series)),
        })

    for a_i in range(len(cols)):
        for b_i in range(a_i + 1, len(cols)):
            a, b = cols[a_i], cols[b_i]
            calc = F.pearson_r(df[a].tolist(), df[b].tolist(), a, b)
            if calc.value is None or abs(calc.value) < min_abs_r:
                continue
            r = calc.value
            strength = ("very strong" if abs(r) >= 0.8 else
                        "strong" if abs(r) >= 0.6 else
                        "moderate" if abs(r) >= 0.4 else "weak")
            edges.append({
                "source": a, "target": b,
                "r": round(r, 3),
                "abs_r": round(abs(r), 3),
                "direction": "positive" if r > 0 else "negative",
                "strength": strength,
                "r_squared": round(r * r, 3),
                "interpretation": (
                    f"{PRETTY.get(a,a)} and {PRETTY.get(b,b)} have a {strength} "
                    f"{'positive' if r>0 else 'negative'} relationship "
                    f"(r = {r:+.3f}); {r*r*100:.1f} % of the variation in one is "
                    f"tracked by the other."
                ),
            })
            calcs.append(calc.to_dict())

    edges.sort(key=lambda e: -e["abs_r"])
    table_rows = [[PRETTY.get(e["source"], e["source"]), PRETTY.get(e["target"], e["target"]),
                   f"{e['r']:+.3f}", e["strength"], e["direction"], f"{e['r_squared']:.3f}"]
                  for e in edges]

    return {
        "nodes": nodes,
        "edges": edges,
        "table": {
            "title": f"Correlation matrix -- {len(df):,} samples over {days} days",
            "columns": ["Variable A", "Variable B", "Pearson r", "Strength",
                        "Direction", "R-squared"],
            "rows": table_rows,
        },
        "formulas": calcs[:6],
        "notes": [
            "Pearson r measures linear association only, and correlation is not causation.",
            f"Computed on {len(df):,} samples; pairs weaker than |r| = {min_abs_r} are hidden.",
        ],
    }


