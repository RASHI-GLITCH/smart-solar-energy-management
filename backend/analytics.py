# Fault detection  (deterministic checks, PDF section 13)
# ---------------------------------------------------------------------------
def health_check(reading: Optional[Dict] = None) -> Dict:
    from .datasource import get_latest
    r = reading or get_latest()
    faults, warnings_ = [], []

    if not r.get("ok"):
        return {"status": "FAULT", "faults": ["No data available from the source."],
                "warnings": [], "checks": []}

    checks = []

    def check(name, value, lo, hi, unit):
        if value is None:
            faults.append(f"{name} is missing from the feed.")
            checks.append([name, "missing", f"{lo} .. {hi} {unit}", "FAIL"])
            return
        ok = lo <= value <= hi
        (checks.append([name, f"{value:.2f} {unit}", f"{lo} .. {hi} {unit}",
                        "PASS" if ok else "FAIL"]))
        if not ok:
            faults.append(f"{name} is {value:.2f} {unit}, outside the safe range "
                          f"{lo} .. {hi} {unit}.")

    s = C.SAFETY
    check("Panel voltage", _num(r.get("voltage")), s["voltage_min"], s["voltage_max"], "V")
    check("Panel current", _num(r.get("current")), s["current_min"], s["current_max"], "A")
    check("Temperature", _num(r.get("temperature")), s["temperature_min"], s["temperature_max"], "degC")
    check("Battery voltage", _num(r.get("battery_v")), s["battery_v_min"], s["battery_v_max"], "V")

    age = r.get("age_seconds", 0) or 0
    fresh_ok = age <= s["data_max_age_s"]
    checks.append(["Data freshness", f"{age:.0f} s", f"<= {s['data_max_age_s']} s",
                   "PASS" if fresh_ok else "FAIL"])
    if not fresh_ok:
        faults.append(f"Data is {age:.0f} s old (limit {s['data_max_age_s']} s). "
                      "Treated as stale -- the agent will not act on it.")

    soc = F.soc_from_voltage(_num(r.get("battery_v")) or C.BATTERY_NOMINAL_V)
    soc_v = soc.value or 0
    if soc_v < s["soc_critical"]:
        faults.append(f"Battery critically low at {soc_v:.1f} % "
                      f"(threshold {s['soc_critical']} %).")
    elif soc_v < s["soc_low"]:
        warnings_.append(f"Battery low at {soc_v:.1f} % (threshold {s['soc_low']} %).")
    checks.append(["Battery SOC", f"{soc_v:.1f} %", f">= {s['soc_critical']} %",
                   "PASS" if soc_v >= s["soc_critical"] else "FAIL"])

    # Sustained prediction residual -- the PDF's e(t) check
    residual_note = None
    df = get_history(days=2)
    if len(df) > 60:
        recent = df.tail(60).copy()
        exp = []
        for _, row in recent.iterrows():
            irr = F.irradiance_from_light(float(row.get("light") or 0)).value or 0
            ct = F.cell_temperature(float(row.get("temperature") or 25), irr).value or 25
            exp.append(F.temperature_derated_power(irr, ct).value or 0)
        recent["expected"] = exp
        daylight = recent[recent["expected"] > 2.0]
        if len(daylight) > 15:
            mean_res = float((daylight["power"].fillna(0) - daylight["expected"]).mean())
            mean_exp = float(daylight["expected"].mean())
            pct = mean_res / mean_exp * 100 if mean_exp > 1e-6 else 0
            checks.append(["Prediction residual", f"{mean_res:+.2f} W ({pct:+.1f} %)",
                           "within +/- 25 %", "PASS" if abs(pct) <= 25 else "FAIL"])
            if pct < -25:
                warnings_.append(
                    f"Panel is producing {abs(pct):.0f} % below the physics model over the "
                    f"last {len(daylight)} daylight samples. Possible soiling, shading or "
                    f"sensor drift -- worth investigating, not proof of a fault.")
                residual_note = mean_res

    status = "FAULT" if faults else ("WARNING" if warnings_ else "HEALTHY")
    return {
        "status": status,
        "faults": faults,
        "warnings": warnings_,
        "table": {
            "title": "System health checks",
            "columns": ["Check", "Measured", "Acceptable range", "Result"],
            "rows": checks,
        },
        "formulas": [soc.to_dict()],
        "residual_w": residual_note,
        "notes": ["All checks are deterministic range and freshness tests, "
                  "evaluated before the LLM sees anything."],
    }


def _num(x):
    try:
        if x is None or (isinstance(x, float) and math.isnan(x)):
            return None
        return float(x)
    except (TypeError, ValueError):
        return None


# ---------------------------------------------------------------------------
# Time series for the dashboard charts
# ---------------------------------------------------------------------------
def timeseries(hours: int = 24, max_points: int = 300) -> Dict:
    df = get_history()
    if df.empty:
        return {"points": []}
    cutoff = df["timestamp"].max() - timedelta(hours=hours)
    win = df[df["timestamp"] >= cutoff]
    if len(win) > max_points:
        win = win.iloc[:: max(1, len(win) // max_points)]
    return {
        "points": [
            {
                "t": ts.isoformat(),
                "power": _round(r.get("power")),
                "load": _round(r.get("load_power")),
                "battery_v": _round(r.get("battery_v"), 3),
                "soc": _round(F.soc_from_voltage(float(r.get("battery_v") or 12)).value, 1),
                "light": _round(r.get("light"), 0),
                "temperature": _round(r.get("temperature"), 1),
            }
            for ts, r in zip(win["timestamp"], win.to_dict("records"))
        ]
    }


def _round(x, nd: int = 2):
    try:
        if x is None or (isinstance(x, float) and math.isnan(x)):
            return None
        return round(float(x), nd)
    except (TypeError, ValueError):
        return None
