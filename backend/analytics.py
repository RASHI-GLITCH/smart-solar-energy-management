"""
Deterministic analytics. No LLM, no ML -- just physics and arithmetic.

Every public function returns a dict shaped like:

    {
      "headline":  {...}            # the single number that answers the question
      "table":     {columns, rows}  # numbers laid out for display
      "formulas":  [ ...Calc... ]   # how each number was derived
      "notes":     [ "..." ]        # caveats the agent must not omit
    }

The agent reads these and narrates them. It never does arithmetic itself,
which is what keeps the answers exact.
"""
import math
from datetime import datetime, timedelta
from typing import Dict, List, Optional

import numpy as np
import pandas as pd

from . import config as C
from . import formulas as F
from .datasource import get_history
from .simulator import _clear_sky_irradiance, _solar_elevation


def _interval_seconds(df: pd.DataFrame) -> float:
    if len(df) < 2:
        return 60.0
    deltas = df["timestamp"].diff().dt.total_seconds().dropna()
    med = float(deltas.median())
    return med if 1.0 <= med <= 3600.0 else 60.0


def _window(df: pd.DataFrame, period: str) -> (pd.DataFrame, str):
    """Slice a frame by a plain-language period name."""
    if df.empty:
        return df, period
    now = df["timestamp"].max()
    today = now.normalize()
    period = (period or "today").lower().strip()

    if period in ("today", "day"):
        return df[df["timestamp"] >= today], "today"
    if period == "yesterday":
        start = today - timedelta(days=1)
        return df[(df["timestamp"] >= start) & (df["timestamp"] < today)], "yesterday"
    if period in ("hour", "last_hour", "past_hour"):
        return df[df["timestamp"] >= now - timedelta(hours=1)], "the last hour"
    if period in ("week", "last_week", "7d"):
        return df[df["timestamp"] >= now - timedelta(days=7)], "the last 7 days"
    if period in ("month", "30d"):
        return df[df["timestamp"] >= now - timedelta(days=30)], "the last 30 days"
    if period in ("all", "everything", "total"):
        return df, "the full record"
    return df[df["timestamp"] >= today], "today"


# ---------------------------------------------------------------------------
# Energy summary  (generation, consumption, cost, CO2)
# ---------------------------------------------------------------------------
def energy_summary(period: str = "today") -> Dict:
    df = get_history()
    win, label = _window(df, period)
    if win.empty:
        return {"error": f"No data available for {label}.", "period": label}

    dt_s = _interval_seconds(win)
    hours = len(win) * dt_s / 3600.0

    gen = F.energy_from_samples(win["power"].fillna(0).tolist(), dt_s)
    gen.key, gen.name = "energy_generated", "Energy generated by the panel"
    load_series = win["load_power"].fillna(0).tolist() if "load_power" in win else []
    con = F.energy_from_samples(load_series, dt_s)
    con.key, con.name = "energy_consumed", "Energy consumed by the load"
    avg_gen = F.mean_power(gen.value or 0, hours)
    avg_gen.key, avg_gen.name = "avg_generation", "Average generation"
    avg_con = F.mean_power(con.value or 0, hours)
    avg_con.key, avg_con.name = "avg_consumption", "Average consumption"
    net = F.net_energy(gen.value or 0, con.value or 0)
    suff = F.self_sufficiency(gen.value or 0, con.value or 0)
    saving = F.cost_saving(min(gen.value or 0, con.value or 0))
    co2 = F.co2_avoided(min(gen.value or 0, con.value or 0))

    peak_idx = win["power"].idxmax() if win["power"].notna().any() else None
    peak_w = float(win.loc[peak_idx, "power"]) if peak_idx is not None else 0.0
    peak_t = win.loc[peak_idx, "timestamp"] if peak_idx is not None else None

    # Hourly breakdown table
    hourly = (win.set_index("timestamp")
                 .resample("1h")
                 .agg(gen_w=("power", "mean"),
                      load_w=("load_power", "mean"),
                      batt_v=("battery_v", "mean")))
    rows = []
    for ts, r in hourly.iterrows():
        g = 0.0 if pd.isna(r.gen_w) else float(r.gen_w)
        l = 0.0 if pd.isna(r.load_w) else float(r.load_w)
        rows.append([ts.strftime("%d %b %H:%M"), round(g, 1), round(l, 1),
                     round(g - l, 1), round(g * 1.0, 1), round(l * 1.0, 1)])

    return {
        "period": label,
        "headline": {
            "generated_wh": round(gen.value or 0, 1),
            "consumed_wh": round(con.value or 0, 1),
            "net_wh": round(net.value or 0, 1),
            "peak_power_w": round(peak_w, 1),
            "peak_at": peak_t.strftime("%d %b %H:%M") if peak_t is not None else None,
            "self_sufficiency_pct": round(suff.value, 1) if suff.value else None,
            "cost_saved_inr": round(saving.value or 0, 2),
            "co2_avoided_kg": round(co2.value or 0, 3),
            "samples": int(len(win)),
            "hours_covered": round(hours, 2),
        },
        "table": {
            "title": f"Hourly energy breakdown -- {label}",
            "columns": ["Hour", "Avg generation (W)", "Avg load (W)", "Net (W)",
                        "Energy generated (Wh)", "Energy used (Wh)"],
            "rows": rows,
        },
        "formulas": [c.to_dict() for c in (gen, con, avg_gen, avg_con, net, suff, saving, co2)],
        "notes": [
            f"Computed from {len(win):,} samples at a {dt_s:.0f} s interval.",
            "Cost and CO2 credit only the solar energy that actually displaced load.",
        ],
    }


# ---------------------------------------------------------------------------
# Forecast  (solar geometry + observed performance ratio -- no ML)
# ---------------------------------------------------------------------------
def _observed_performance_ratio(df: pd.DataFrame, days: int = 5) -> (float, int, float):
    """
    Compare what the panel actually produced against clear-sky physics over the
    recent past. The resulting ratio bundles cloud cover, soiling, shading,
    wiring loss and panel ageing into one empirically measured number.
    """
    if df.empty:
        return 0.45, 0, 0.0
    cutoff = df["timestamp"].max() - timedelta(days=days)
    recent = df[df["timestamp"] >= cutoff].copy()
    if recent.empty:
        return 0.45, 0, 0.0

    theo = []
    for ts in recent["timestamp"]:
        elev = _solar_elevation(ts.to_pydatetime(), C.SITE_LATITUDE,
                                C.SITE_LONGITUDE, C.TZ_OFFSET_HOURS)
        g = _clear_sky_irradiance(elev)
        theo.append(C.PANEL_RATED_W * (g / 1000.0))
    recent["theoretical_w"] = theo

    daylight = recent[recent["theoretical_w"] > 1.0]
    if daylight.empty:
        return 0.45, 0, 0.0

    actual = float(daylight["power"].fillna(0).sum())
    theoretical = float(daylight["theoretical_w"].sum())
    pr = actual / theoretical if theoretical > 1e-6 else 0.45
    return max(0.05, min(1.0, pr)), len(daylight), pr * 100.0


def forecast(target: str = "tomorrow", date: Optional[str] = None) -> Dict:
    """
    Predict generation for a future day from solar geometry.

    The sun's position for a given latitude and date is exact astronomy, not a
    guess. We scale the resulting clear-sky curve by the performance ratio
    measured in the recent data. Consumption is projected from the observed
    load profile for the same hours.
    """
    df = get_history()
    if df.empty:
        return {"error": "No history available, so no forecast can be made."}

    last_ts = df["timestamp"].max()
    if date:
        try:
            day = pd.to_datetime(date).normalize()
        except Exception:
            return {"error": f"Could not read '{date}' as a date."}
    else:
        offset = {"tomorrow": 1, "today": 0, "day_after_tomorrow": 2}.get(target, 1)
        day = last_ts.normalize() + timedelta(days=offset)

    pr, n_samples, pr_pct = _observed_performance_ratio(df)

    # Hour-by-hour clear-sky curve for that date
    rows, gen_wh_total, theo_wh_total = [], 0.0, 0.0
    hourly_gen = []
    for hour in range(24):
        ts = (day + timedelta(hours=hour)).to_pydatetime()
        elev = _solar_elevation(ts, C.SITE_LATITUDE, C.SITE_LONGITUDE, C.TZ_OFFSET_HOURS)
        g_clear = _clear_sky_irradiance(elev)
        p_theo = C.PANEL_RATED_W * (g_clear / 1000.0)
        p_pred = p_theo * pr
        hourly_gen.append(p_pred)
        theo_wh_total += p_theo
        gen_wh_total += p_pred

    # Load projection: mean observed load for each hour of day
    df = df.copy()
    df["hour"] = df["timestamp"].dt.hour
    load_by_hour = df.groupby("hour")["load_power"].mean().fillna(0).to_dict() \
        if "load_power" in df.columns else {}
    load_wh_total = 0.0

    for hour in range(24):
        p_pred = hourly_gen[hour]
        l_pred = float(load_by_hour.get(hour, 0.0) or 0.0)
        load_wh_total += l_pred
        elev = _solar_elevation((day + timedelta(hours=hour)).to_pydatetime(),
                                C.SITE_LATITUDE, C.SITE_LONGITUDE, C.TZ_OFFSET_HOURS)
        rows.append([
            f"{hour:02d}:00",
            round(max(0.0, elev), 1),
            round(p_pred, 1),
            round(l_pred, 1),
            round(p_pred - l_pred, 1),
            round(p_pred, 1),          # Wh over a 1 h slot equals the average W
            round(l_pred, 1),
        ])

    peak_hour = int(np.argmax(hourly_gen))
    peak_w = float(max(hourly_gen))
    daylight_hours = sum(1 for p in hourly_gen if p > 0.5)

    gen_calc = F.Calc(
        key="forecast_generation",
        name="Predicted generation",
        value=gen_wh_total,
        unit="Wh",
        latex=r"E_{pred} = PR \times \sum_{h=0}^{23} P_{STC}\frac{G_{clear}(h)}{1000} \times 1\,\text{h}",
        substitution=(f"E = {pr:.3f} x {theo_wh_total:,.1f} Wh (clear-sky total) "
                      f"= {gen_wh_total:,.1f} Wh"),
        explanation=(
            "The clear-sky curve comes from the sun's geometric position for this "
            "latitude and date, which is exact astronomy. It is then scaled by the "
            "performance ratio actually measured on this system in recent days."
        ),
        assumptions=[
            f"Performance ratio {pr:.3f} ({pr_pct:.1f} %) measured over {n_samples:,} "
            f"recent daylight samples.",
            "Assumes weather similar to the recent average -- an unusually clear or "
            "overcast day will deviate.",
            "No live weather forecast is used. Adding one would tighten this materially.",
        ],
    )
    pr_calc = F.Calc(
        key="performance_ratio",
        name="Measured performance ratio",
        value=pr_pct,
        unit="%",
        latex=r"PR = \frac{\sum P_{measured}}{\sum P_{clear\text{-}sky}}",
        substitution=f"PR = measured / clear-sky over recent daylight = {pr_pct:.1f} %",
        explanation=("How much of the theoretically available energy this system actually "
                     "captures. Bundles cloud, soiling, shading and wiring losses."),
    )
    load_calc = F.Calc(
        key="forecast_load",
        name="Projected consumption",
        value=load_wh_total,
        unit="Wh",
        latex=r"E_{load} = \sum_{h=0}^{23} \overline{P_{load}}(h) \times 1\,\text{h}",
        substitution=f"E_load = sum of hourly average loads = {load_wh_total:,.1f} Wh",
        explanation=("Consumption is projected from the average load observed at each "
                     "hour of day across the historical record."),
        assumptions=["Assumes usage habits stay the same as the observed average."],
    )
    net_calc = F.net_energy(gen_wh_total, load_wh_total)
    surplus = gen_wh_total - load_wh_total
    batt_cap_wh = C.BATTERY_CAPACITY_AH * C.BATTERY_NOMINAL_V

    return {
        "target_date": day.strftime("%A, %d %B %Y"),
        "headline": {
            "predicted_generation_wh": round(gen_wh_total, 1),
            "predicted_consumption_wh": round(load_wh_total, 1),
            "predicted_net_wh": round(surplus, 1),
            "peak_power_w": round(peak_w, 1),
            "peak_hour": f"{peak_hour:02d}:00",
            "daylight_hours": daylight_hours,
            "performance_ratio_pct": round(pr_pct, 1),
            "battery_capacity_wh": round(batt_cap_wh, 1),
            "verdict": "surplus expected" if surplus >= 0 else "deficit expected",
        },
        "table": {
            "title": f"Hour-by-hour forecast -- {day.strftime('%d %b %Y')}",
            "columns": ["Hour", "Sun elevation (deg)", "Predicted PV (W)",
                        "Projected load (W)", "Net (W)",
                        "PV energy (Wh)", "Load energy (Wh)"],
            "rows": rows,
        },
        "formulas": [c.to_dict() for c in (pr_calc, gen_calc, load_calc, net_calc)],
        "notes": [
            "Forecast is geometric, not meteorological -- it does not know tomorrow's weather.",
            f"Confidence is proportional to how stable the recent performance ratio is "
            f"({pr_pct:.1f} % measured).",
        ],
    }


